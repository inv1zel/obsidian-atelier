export const directionById = (id) => directions.find((d) => d.id === id)
export const serviceById = (id) => services.find((s) => s.id === id)
export const servicesByDir = (dir) => services.filter((s) => s.dir === dir)

export const priceFor = (service, classId) => {
  const k = carClasses.find((c) => c.id === classId)?.k ?? 1
  return Math.round((service.price * k) / 500) * 500
}

export const formatPrice = (n) =>
  n === 0 ? 'Бесплатно' : n.toLocaleString('ru-RU').replace(/,/g, ' ') + ' ₽'

export const formatDuration = (d) => {
  if (d.h) return `${d.h} ч`
  const n = d.d
  const word = n === 1 ? 'день' : n < 5 ? 'дня' : 'дней'
  return `${n} ${word}`
}

// суммарная длительность: часы складываются, дни — тоже; 8 ч = 1 рабочий день
export const totalDuration = (list) => {
  const hours = list.reduce((s, x) => s + (x.duration.h ?? x.duration.d * 8), 0)
  return hours <= 8 ? { h: hours } : { d: Math.ceil(hours / 8) }
}
